import {encodeBlueprintString, createSingleArea, type BlueprintBuildingData} from '@engine/adapters/dsp/blueprint/blueprintData';
import type {CalculatorTableExportSource} from './resultTableExport';

const BLUEPRINT_FILE_MIME_TYPE = 'text/plain;charset=utf-8';
const MAX_BLUEPRINT_BUILDINGS = 600;
const BUILDINGS_PER_ROW = 20;
const BUILDING_GRID_X = 4;
const BUILDING_GRID_Y = 6;

export interface GameBlueprintExportSuccess {
    ok: true;
    blueprint: string;
    buildingCount: number;
    warnings: string[];
}

export interface GameBlueprintExportFailure {
    ok: false;
    errors: string[];
    warnings: string[];
}

export type GameBlueprintExportResult = GameBlueprintExportSuccess | GameBlueprintExportFailure;

type FileSystemWritableFileStreamLike = {
    write(data: Blob): Promise<void>;
    close(): Promise<void>;
};

type FileSystemFileHandleLike = {
    createWritable(): Promise<FileSystemWritableFileStreamLike>;
};

type WindowWithSaveFilePicker = Window & {
    showSaveFilePicker?: (options: {
        suggestedName?: string;
        types?: Array<{
            description: string;
            accept: Record<string, string[]>;
        }>;
    }) => Promise<FileSystemFileHandleLike>;
};

function buildTimestampForFileName(): string {
    const now = new Date();
    const pad = (value: number) => String(value).padStart(2, '0');
    return [
        now.getFullYear(),
        pad(now.getMonth() + 1),
        pad(now.getDate()),
        '-',
        pad(now.getHours()),
        pad(now.getMinutes()),
        pad(now.getSeconds()),
    ].join('');
}

function getFactoryModeParameter(proliferatorMode: number): number {
    // DSPCalculator 的 AddAssembler 写入 isInc ? 0 : 1；这里先按“增产模式”为 0，其余为 1。
    return proliferatorMode === 2 ? 0 : 1;
}

export function buildGameBlueprintExport(source: CalculatorTableExportSource): GameBlueprintExportResult {
    const gameData = source.globalState.effective_game_data;
    const buildings: BlueprintBuildingData[] = [];
    const errors: string[] = [];
    const warnings: string[] = [
        '当前蓝图字符串为第一版真实 DSP 蓝图容器，只生成已设配方的生产建筑；尚未生成传送带、分拣器、物流塔和喷涂机布局。',
    ];

    let blockIndex = 0;
    for (const row of source.rowViewModels) {
        if (row.is_mineralized || row.factory_number <= 0) {
            continue;
        }

        const recipe = gameData.recipe_data[row.recipe_id];
        const factory = gameData.factory_data[recipe["设施"]]?.[row.building_choice];
        const recipeGameId = recipe.gameRecipeId;
        const factoryItemId = factory?.itemId;
        const factoryModelIndex = factory?.modelIndex;

        if (recipeGameId === undefined) {
            errors.push(`${recipe["名称"]} 缺少 RecipeProto.ID，请先用新版 GetDspData 重新导出 raw 数据。`);
            continue;
        }
        if (factoryItemId === undefined || factoryModelIndex === undefined) {
            errors.push(`${factory?.["名称"] ?? row.factory_name} 缺少 itemId/modelIndex，请先用新版 GetDspData 重新导出 raw 数据。`);
            continue;
        }
        if (recipe["模型"] !== undefined && recipe["模型"] !== 'normal') {
            warnings.push(`${recipe["名称"]} 是 ${recipe["模型"]} 模型，暂按普通生产建筑写入配方。`);
        }

        const count = Math.ceil(Number(row.factory_number || 0));
        if (buildings.length + count > MAX_BLUEPRINT_BUILDINGS) {
            errors.push(`蓝图建筑数量超过 ${MAX_BLUEPRINT_BUILDINGS} 个，请先降低目标产量或拆分导出。`);
            break;
        }

        for (let i = 0; i < count; i++) {
            const x = (i % BUILDINGS_PER_ROW) * BUILDING_GRID_X;
            const y = (blockIndex * Math.ceil(count / BUILDINGS_PER_ROW) + Math.floor(i / BUILDINGS_PER_ROW)) * BUILDING_GRID_Y;
            buildings.push({
                index: buildings.length,
                itemId: factoryItemId,
                modelIndex: factoryModelIndex,
                areaIndex: 0,
                localOffsetX: x,
                localOffsetY: y,
                localOffsetZ: 0,
                yaw: 0,
                recipeId: recipeGameId,
                parameters: [getFactoryModeParameter(row.proliferator_mode)],
            });
        }
        blockIndex += Math.max(1, Math.ceil(count / BUILDINGS_PER_ROW));
    }

    if (buildings.length === 0) {
        errors.push('当前结果里没有可写入蓝图的生产建筑。');
    }
    if (errors.length > 0) {
        return {
            ok: false,
            errors,
            warnings,
        };
    }

    const maxX = Math.max(...buildings.map(building => building.localOffsetX), 0);
    const maxY = Math.max(...buildings.map(building => building.localOffsetY), 0);
    const width = Math.ceil(maxX + BUILDING_GRID_X);
    const height = Math.ceil(maxY + BUILDING_GRID_Y);

    return {
        ok: true,
        blueprint: encodeBlueprintString({
            shortDesc: 'DSPCalc Factories',
            desc: 'Generated by dsp-calc. Factories only.',
            dragBoxSizeX: width,
            dragBoxSizeY: height,
            areas: [createSingleArea(width, height)],
            buildings,
        }),
        buildingCount: buildings.length,
        warnings,
    };
}

export function buildGameBlueprintFileName(): string {
    return `DSPCalc-${buildTimestampForFileName()}.txt`;
}

export async function saveGameBlueprintFile(blueprint: string, fileName = buildGameBlueprintFileName()): Promise<string> {
    const blob = new Blob([blueprint], {type: BLUEPRINT_FILE_MIME_TYPE});
    const maybePicker = window as WindowWithSaveFilePicker;

    if (maybePicker.showSaveFilePicker) {
        const handle = await maybePicker.showSaveFilePicker({
            suggestedName: fileName,
            types: [{
                description: 'Dyson Sphere Program Blueprint',
                accept: {'text/plain': ['.txt']},
            }],
        });
        const writable = await handle.createWritable();
        await writable.write(blob);
        await writable.close();
        return fileName;
    }

    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = fileName;
    document.body.appendChild(anchor);
    anchor.click();
    document.body.removeChild(anchor);
    URL.revokeObjectURL(url);
    return fileName;
}
